// ─────────────────────────────────────────────
// timeAgo 테스트 — "10분 전" 만들기
//
// 서버는 시각만 주고 문구는 화면에서 만들어요 (D-25).
// 시간대를 잘못 읽으면 방금 쓴 글이 "9시간 전" 이 돼요.
// ─────────────────────────────────────────────
import { describe, expect, it } from "vitest";

import { timeAgo } from "./timeAgo";

/** 2026-08-27 22:00 (한국 시간) */
const 지금 = new Date("2026-08-27T22:00:00+09:00").getTime();

describe("얼마나 지났나", () => {
  it("1분이 안 지났으면 null — '방금' 은 부르는 쪽에서 붙여요", () => {
    expect(timeAgo("2026-08-27T21:59:30+09:00", "ko", 지금)).toBeNull();
    expect(timeAgo("2026-08-27T22:00:00+09:00", "ko", 지금)).toBeNull();
  });

  it("분·시간·일 단위로 바뀐다", () => {
    expect(timeAgo("2026-08-27T21:50:00+09:00", "ko", 지금)).toBe("10분 전");
    expect(timeAgo("2026-08-27T19:00:00+09:00", "ko", 지금)).toBe("3시간 전");
    // 날 단위는 "2일 전" 대신 "그저께" 처럼 자연스러운 말로 나와요
    // (Intl 의 numeric: "auto" 덕분이에요. 아이 앱에 더 어울려요)
    expect(timeAgo("2026-08-26T22:00:00+09:00", "ko", 지금)).toBe("어제");
    expect(timeAgo("2026-08-25T22:00:00+09:00", "ko", 지금)).toBe("그저께");
  });

  it("언어마다 알아서 바뀐다 (사전에 안 적어도 돼요)", () => {
    expect(timeAgo("2026-08-27T21:50:00+09:00", "en", 지금)).toBe("10 minutes ago");
    expect(timeAgo("2026-08-27T21:50:00+09:00", "ja", 지금)).toContain("10");
    expect(timeAgo("2026-08-27T21:50:00+09:00", "zh", 지금)).toContain("10");
  });
});

describe("시간대", () => {
  it("시간대가 붙어 있으면 어느 나라에서 봐도 같은 값", () => {
    // 서버가 +09:00 을 붙여 보내는 이유예요.
    // 같은 순간을 다르게 적어도 "10분 전" 이 나와야 해요
    const 한국표기 = timeAgo("2026-08-27T21:50:00+09:00", "ko", 지금);
    const 세계시표기 = timeAgo("2026-08-27T12:50:00+00:00", "ko", 지금);
    expect(한국표기).toBe(세계시표기);
  });

  it("읽을 수 없는 값은 null (화면이 깨지지 않게)", () => {
    expect(timeAgo("어제쯤", "ko", 지금)).toBeNull();
    expect(timeAgo("", "ko", 지금)).toBeNull();
  });
});
